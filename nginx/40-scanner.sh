#!/bin/sh
# Renders runtime nginx snippets from environment variables.
#   SCANNER_UPSTREAM  backend host name (default: scanner)
#   TRUSTED_PROXIES   comma-separated IPs/CIDRs of reverse proxies in front of
#                     this nginx. Only these may set X-Forwarded-For.
#   HTTP_MODE         redirect (default): port 8080 redirects to https
#                     proxy: port 8080 serves the dashboard, but only to
#                     TRUSTED_PROXIES (for proxies that terminate TLS and
#                     forward plain HTTP)
#   PUBLIC_HTTPS_PORT port users type in the browser for the redirect (default 8443)
#   ADMIN_ALLOW       optional extra comma-separated CIDRs allowed on the admin port
set -eu
GEN=/etc/nginx/generated
mkdir -p "$GEN"

: "${SCANNER_UPSTREAM:=scanner}"
: "${HTTP_MODE:=redirect}"
: "${PUBLIC_HTTPS_PORT:=8443}"
: "${TRUSTED_PROXIES:=}"
: "${ADMIN_ALLOW:=}"
: "${PUBLIC_HOST:=}"   # optional: fixed host name for the http->https redirect

valid_cidr() { echo "$1" | grep -Eq '^([0-9]{1,3}\.){3}[0-9]{1,3}(/[0-9]{1,2})?$|^[0-9a-fA-F:]+(/[0-9]{1,3})?$'; }

# --- real ip ---
: > "$GEN/realip.conf"
proxies=""
for p in $(echo "$TRUSTED_PROXIES" | tr ',' ' '); do
  if valid_cidr "$p"; then
    echo "set_real_ip_from $p;" >> "$GEN/realip.conf"
    proxies="$proxies $p"
  else
    echo "40-scanner: ignoring invalid TRUSTED_PROXIES entry '$p'" >&2
  fi
done
if [ -n "$proxies" ]; then
  printf 'real_ip_header X-Forwarded-For;\nreal_ip_recursive on;\n' >> "$GEN/realip.conf"
fi

# --- admin allow-list (defence in depth; the port binding is the main control) ---
: > "$GEN/admin-allow.conf"
if [ -n "$ADMIN_ALLOW" ]; then
  for p in $(echo "$ADMIN_ALLOW" | tr ',' ' '); do
    valid_cidr "$p" && echo "allow $p;" >> "$GEN/admin-allow.conf"
  done
  printf 'allow 127.0.0.1;\nallow ::1;\ndeny all;\n' >> "$GEN/admin-allow.conf"
fi

# --- plain http server ---
case "$HTTP_MODE" in
  proxy)
    if [ -z "$proxies" ]; then
      echo "40-scanner: HTTP_MODE=proxy needs TRUSTED_PROXIES; falling back to redirect" >&2
      HTTP_MODE=redirect
    fi
    ;;
  redirect) ;;
  *) echo "40-scanner: unknown HTTP_MODE '$HTTP_MODE', using redirect" >&2; HTTP_MODE=redirect ;;
esac

if [ "$HTTP_MODE" = proxy ]; then
  # $realip_remote_addr is the TCP peer (before X-Forwarded-For rewriting), so
  # only the proxies themselves can use this plain-HTTP port.
  {
    echo "geo \$realip_remote_addr \$from_trusted_proxy {"
    echo "    default 0;"
    for p in $proxies; do echo "    $p 1;"; done
    echo "}"
    cat <<'CONF'
server {
    listen 8080 default_server;
    server_name _;
    root /usr/share/nginx/html;
    index index.html;
    if ($from_trusted_proxy = 0) { return 403; }
    include /etc/nginx/security-headers.conf;
    location = /admin.html { return 404; }
    location = /assets/admin.js { return 404; }
    location ^~ /api/admin/ { return 404; }
    location = /metrics { return 404; }
    # Pass the proxy's scheme on, so the backend only sets Secure cookies
    # when the browser is really on https. (Setting one proxy header here
    # drops the inherited ones, so all of them are repeated.)
    location = /api/auth/login { limit_req zone=login burst=5 nodelay; proxy_set_header Connection ""; proxy_set_header Host $host; proxy_set_header X-Real-IP $remote_addr; proxy_set_header X-Forwarded-For $remote_addr; proxy_set_header X-Forwarded-Proto $http_x_forwarded_proto; proxy_pass http://dashboard_api; }
    location /api/ { limit_req zone=api burst=60 nodelay; proxy_set_header Connection ""; proxy_set_header Host $host; proxy_set_header X-Real-IP $remote_addr; proxy_set_header X-Forwarded-For $remote_addr; proxy_set_header X-Forwarded-Proto $http_x_forwarded_proto; proxy_pass http://dashboard_api; }
    location / { try_files $uri /index.html; }
}
CONF
  } > "$GEN/http.conf"
else
  REDIRECT_HOST='$host'
  if [ -n "$PUBLIC_HOST" ]; then
    echo "$PUBLIC_HOST" | grep -Eq '^[A-Za-z0-9.-]+$' && REDIRECT_HOST="$PUBLIC_HOST"
  fi
  cat > "$GEN/http.conf" <<CONF
server {
    listen 8080 default_server;
    server_name _;
    location / { return 308 https://${REDIRECT_HOST}:${PUBLIC_HTTPS_PORT}\$request_uri; }
}
CONF
fi

# --- upstream host ---
echo "$SCANNER_UPSTREAM" | grep -Eq '^[A-Za-z0-9.-]+$' || { echo "40-scanner: bad SCANNER_UPSTREAM" >&2; exit 1; }
sed -i "s/\${SCANNER_UPSTREAM}/${SCANNER_UPSTREAM}/g" /etc/nginx/nginx.conf

# --- wait for the TLS certificate (generated by the scanner on first start) ---
i=0
while [ ! -s /certs/cert.pem ] || [ ! -s /certs/key.pem ]; do
  i=$((i+1))
  if [ "$i" -gt 60 ]; then echo "40-scanner: no certificate in /certs after 60s" >&2; exit 1; fi
  sleep 1
done
echo "40-scanner: http_mode=$HTTP_MODE trusted_proxies='${TRUSTED_PROXIES}'"
